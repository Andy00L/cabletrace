import { createHash } from "node:crypto";
import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";

// The content versions of public/seabed's files, shared by the script that writes src/lib/seabed/seabed-file-versions.ts
// and the test that checks it. Each version is the first 12 hex digits of the file's SHA-256: the 3D replay puts it in
// the file's URL, so a year of immutable caching (next.config.ts, /seabed/:path*) still serves a changed file.

const REPOSITORY_ROOT = path.resolve(import.meta.dir, "../..");
export const SEABED_PUBLIC_DIRECTORY = path.join(REPOSITORY_ROOT, "public", "seabed");
export const SEABED_FILE_VERSIONS_PATH = path.join(REPOSITORY_ROOT, "src", "lib", "seabed", "seabed-file-versions.ts");
// Hex digits kept of each SHA-256: 48 bits, so two versions of one file never collide in practice.
const VERSION_LENGTH = 12;

/** Every file in public/seabed with its version, by name, in name order. */
export function measureSeabedFileVersions(): [string, string][] {
  return readdirSync(SEABED_PUBLIC_DIRECTORY)
    .filter((name) => name.endsWith(".json") || name.endsWith(".bin") || name.endsWith(".js"))
    .sort()
    .map((name) => [name, createHash("sha256").update(readFileSync(path.join(SEABED_PUBLIC_DIRECTORY, name))).digest("hex").slice(0, VERSION_LENGTH)]);
}

/** The TypeScript module src/lib/seabed/seabed-file-versions.ts must hold for these versions. */
export function writeSeabedFileVersionsModule(versions: readonly [string, string][]): string {
  const entries = versions.map(([name, version]) => `  "${name}": "${version}",`).join("\n");
  return `// Generated by scripts/seabed/build-seabed-file-versions.ts from the files in public/seabed. Do not edit: run the script
// after changing a file there (seabed-file-versions.test.ts fails until then).

/** A short content hash of each file in public/seabed, by file name; seabed-urls.ts puts it in the file's URL. */
export const SEABED_FILE_VERSIONS: Readonly<Record<string, string>> = {
${entries}
};
`;
}

// Builds src/lib/globe/maritime-identification-digits.ts, the ITU table of Maritime Identification Digits (the first
// three digits of a ship station's MMSI name the administration that assigned it), from ITU's own page.
// Usage:
//   curl -s https://www.itu.int/gladapp/Allocation/MIDs > .scratch/itu-mids.html
//   bun scripts/globe/build-mid-table.ts .scratch/itu-mids.html
// Source: ITU-R, Table of Maritime Identification Digits, https://www.itu.int/gladapp/Allocation/MIDs (the table the
// page https://www.itu.int/en/ITU-R/terrestrial/fmd/Pages/mid.aspx embeds).
import { readFile, writeFile } from "node:fs/promises";

const OUTPUT_PATH = "src/lib/globe/maritime-identification-digits.ts";
const ROW_PATTERN = /<tr[^>]*>([\s\S]*?)<\/tr>/g;
const CELL_PATTERN = /<t[dh][^>]*>([\s\S]*?)<\/t[dh]>/g;
const HTML_ENTITIES: Readonly<Record<string, string>> = { "&amp;": "&", "&#39;": "'", "&quot;": '"', "&lt;": "<", "&gt;": ">", "&nbsp;": " " };

function toText(cellHtml: string): string {
  return cellHtml
    .replace(/<[^>]+>/g, "")
    .replace(/&[a-z#0-9]+;/gi, (entity) => HTML_ENTITIES[entity] ?? entity)
    .replace(/\s+/g, " ")
    .trim();
}

async function main(): Promise<number> {
  const inputPath = process.argv[2];
  if (!inputPath) {
    console.error("[buildMidTable] pass the path to the saved ITU page");
    return 2;
  }
  let html: string;
  try {
    html = await readFile(inputPath, "utf8");
  } catch (error) {
    console.error(`[buildMidTable] could not read ${inputPath}: ${error instanceof Error ? error.message : String(error)}`);
    return 2;
  }
  const entries: [number, string][] = [];
  for (const row of html.matchAll(ROW_PATTERN)) {
    const cells = [...(row[1] ?? "").matchAll(CELL_PATTERN)].map((cell) => toText(cell[1] ?? ""));
    const [digitsCell, administration] = cells;
    if (!digitsCell || !administration) continue;
    // An administration with several MIDs lists them all in one cell (Panama: 351 to 357, 370 to 374).
    const allDigits = digitsCell.split(" ").filter((digits) => /^[2-7]\d\d$/.test(digits));
    allDigits.forEach((digits) => entries.push([Number(digits), administration]));
  }
  if (entries.length < 200) {
    console.error(`[buildMidTable] only ${entries.length} rows found: not the ITU table`);
    return 1;
  }
  entries.sort((first, second) => first[0] - second[0]);
  const lines = entries.map(([digits, administration]) => `  [${digits}, ${JSON.stringify(administration)}],`);
  const output = `// Generated by scripts/globe/build-mid-table.ts from the ITU table of Maritime Identification Digits
// (https://www.itu.int/gladapp/Allocation/MIDs, read ${new Date().toISOString().slice(0, 10)}). Do not edit by hand: rerun the script.

/** Administration (country or territory, as ITU names it) by Maritime Identification Digits. */
export const MARITIME_IDENTIFICATION_DIGITS: ReadonlyMap<number, string> = new Map([
${lines.join("\n")}
]);
`;
  await writeFile(OUTPUT_PATH, output);
  console.log(`[buildMidTable] ${entries.length} MIDs to ${OUTPUT_PATH}`);
  return 0;
}

process.exit(await main());

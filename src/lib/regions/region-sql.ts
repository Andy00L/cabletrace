// SQL text generated from the registry, so the database's copy of each region and its cable seed come from one source
// of truth. scripts/regions/build-regions-sql.ts and scripts/regions/build-cable-seed.ts write these into migrations;
// src/lib/regions/region-sql.test.ts checks that the committed migrations still match the registry.
import type { Coordinate, SeedLine } from "@/lib/regions/line-network";
import type { LineSource, LineSourceId, LiveSource, LiveSourceId, Region } from "@/lib/regions/region";
import { effectiveRetentionHours } from "@/lib/regions/region";

// Five decimals of a degree is 1.1 m or less: finer than the 100 m simplification, coarser would move points.
const COORDINATE_DECIMALS = 5;

/** A SQL string literal: single quotes doubled, nothing else needs escaping with standard_conforming_strings on. */
export function quoteSqlText(text: string): string {
  return `'${text.replaceAll("'", "''")}'`;
}

function formatNumber(value: number): string {
  // No exponent notation and no trailing ".0" noise: the generated files diff cleanly.
  return Number.isInteger(value) ? String(value) : String(Number(value.toFixed(6)));
}

function formatCoordinate([longitude, latitude]: Coordinate): string {
  return `${longitude.toFixed(COORDINATE_DECIMALS)} ${latitude.toFixed(COORDINATE_DECIMALS)}`;
}

export function toMultiLineStringWkt(parts: readonly Coordinate[][]): string {
  return `MULTILINESTRING(${parts.map((part) => `(${part.map(formatCoordinate).join(", ")})`).join(", ")})`;
}

/** True when every source of the region lets positions be kept past the hot window (and so archived). */
export function isArchivedRegion(region: Region, liveSources: Readonly<Record<LiveSourceId, LiveSource>>): boolean {
  return region.liveSources.every((sourceId) => liveSources[sourceId].maxRetentionHours === null);
}

/** The upsert of every region into public.watched_regions (supabase/migrations/20261019100000_watched_regions.sql). */
export function buildWatchedRegionsSql(regions: readonly Region[], liveSources: Readonly<Record<LiveSourceId, LiveSource>>): string {
  const rows = regions.map((region) => {
    const { box, recording } = region;
    const values = [
      quoteSqlText(region.id),
      quoteSqlText(region.name),
      `extensions.st_makeenvelope(${formatNumber(box.west)}, ${formatNumber(box.south)}, ${formatNumber(box.east)}, ${formatNumber(box.north)}, 4326)`,
      quoteSqlText(region.timeZone),
      `array[${region.liveSources.map(quoteSqlText).join(", ")}]`,
      formatNumber(recording.nearCableMetres),
      formatNumber(recording.candidateCableMetres),
      formatNumber(recording.stationaryKnots),
      formatNumber(recording.stationaryRepeatMinutes),
      formatNumber(recording.stationaryRepeatMetres),
      formatNumber(effectiveRetentionHours(region, liveSources)),
      String(isArchivedRegion(region, liveSources)),
    ];
    return `  (${values.join(", ")})`;
  });
  return [
    "insert into public.watched_regions (",
    "  id, name, box, time_zone, live_sources, near_cable_metres, candidate_cable_metres, stationary_knots,",
    "  stationary_repeat_minutes, stationary_repeat_metres, hot_retention_hours, is_archived",
    ") values",
    `${rows.join(",\n")}`,
    "on conflict (id) do update set",
    "  name = excluded.name,",
    "  box = excluded.box,",
    "  time_zone = excluded.time_zone,",
    "  live_sources = excluded.live_sources,",
    "  near_cable_metres = excluded.near_cable_metres,",
    "  candidate_cable_metres = excluded.candidate_cable_metres,",
    "  stationary_knots = excluded.stationary_knots,",
    "  stationary_repeat_minutes = excluded.stationary_repeat_minutes,",
    "  stationary_repeat_metres = excluded.stationary_repeat_metres,",
    "  hot_retention_hours = excluded.hot_retention_hours,",
    "  is_archived = excluded.is_archived;",
  ].join("\n");
}

function sourceUrlOf(line: SeedLine, source: LineSource): string {
  // An OpenStreetMap line links its first way, so anyone can open the mapped object and its history.
  return line.sourceId === "openstreetmap" && line.sourceRef.startsWith("way/") ? `https://www.openstreetmap.org/${line.sourceRef}` : source.url;
}

/** One region's cable seed: an idempotent upsert per line into public.cables. */
export function buildCableSeedSql(region: Region, lines: readonly SeedLine[], lineSources: Readonly<Record<LineSourceId, LineSource>>): string {
  const header = [
    `-- Cables and pipelines of ${region.name} (${region.id}: ${region.box.west} to ${region.box.east} E, ${region.box.south} to ${region.box.north} N),`,
    `-- generated by scripts/regions/build-cable-seed.ts from ${[...new Set(lines.map((line) => lineSources[line.sourceId].name))].join(", ") || "no source line"}.`,
    ...[...new Set(lines.map((line) => line.sourceId))].map((sourceId) => `-- ${lineSources[sourceId].credit}: ${lineSources[sourceId].url}`),
    `-- ${lines.length} lines, ${lines.reduce((total, line) => total + line.parts.reduce((partTotal, part) => partTotal + part.length, 0), 0)} points; regenerate rather than edit.`,
    "",
  ];
  const statements = lines.map((line) => {
    const source = lineSources[line.sourceId];
    const values = [
      quoteSqlText(region.id),
      quoteSqlText(line.name),
      quoteSqlText(line.kind),
      quoteSqlText(source.credit),
      quoteSqlText(source.licence),
      quoteSqlText(sourceUrlOf(line, source)),
      `extensions.st_geogfromtext(${quoteSqlText(`SRID=4326;${toMultiLineStringWkt(line.parts)}`)})`,
    ];
    return (
      `insert into public.cables (region_id, name, kind, source, licence, source_url, route) values (${values.join(", ")})\n` +
      "on conflict (region_id, name, kind) do update set source = excluded.source, licence = excluded.licence, source_url = excluded.source_url, route = excluded.route;"
    );
  });
  return `${[...header, ...statements].join("\n")}\n`;
}

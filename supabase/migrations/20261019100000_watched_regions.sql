-- The Gulf of Finland routes clipped below come back by re-running the statements of 20261017020100_seed_gulf_cables.sql
-- as updates of `route` by name and kind.

create table public.watched_regions (
  id text primary key check (id ~ '^[a-z]+(-[a-z]+)*$'),
  name text not null,
  box extensions.geometry(Polygon, 4326) not null,
  time_zone text not null,
  -- LiveSourceId in src/lib/regions/region.ts.
  live_sources text[] not null check (cardinality(live_sources) > 0 and live_sources <@ array['digitraffic', 'aisstream']),
  near_cable_metres double precision not null check (near_cable_metres > 0),
  -- RecordingThresholds.candidateCableMetres: how close a drag-band report must come to a cable for the ship's track to
  -- reach the detector.
  candidate_cable_metres double precision not null check (candidate_cable_metres > 0 and candidate_cable_metres <= near_cable_metres),
  stationary_knots real not null check (stationary_knots >= 0),
  stationary_repeat_minutes integer not null check (stationary_repeat_minutes > 0),
  stationary_repeat_metres double precision not null check (stationary_repeat_metres > 0),
  -- Already capped by the strictest feed (effectiveRetentionHours): 47 for aisstream, which publishes no terms.
  hot_retention_hours integer not null check (hot_retention_hours > 0),
  -- True when every feed allows keeping positions past the hot window: old days then move to Storage files.
  is_archived boolean not null
);
create index watched_regions_box_index on public.watched_regions using gist (box);

alter table public.watched_regions enable row level security;
create policy "Watched regions are readable by everyone" on public.watched_regions for select to anon, authenticated using (true);


-- Watched regions as data: the database's copy of the registry in src/data/regions (src/lib/regions/region.ts), which
-- the recorder's SQL reads for each region's box, feeds and thresholds. public.cables gains the region it belongs to,
-- its licence and a link to its source. The cable seeds of the seven new regions follow (20261019100100 to 100700).
--
-- Rollback (in this order, after the seed migrations' own rollback):

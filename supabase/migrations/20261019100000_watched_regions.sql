-- Every cable belongs to one region; a cable crossing two regions is seeded once per region, clipped to each box.
alter table public.cables
  add column region_id text references public.watched_regions (id),
  add column licence text,
  add column source_url text;

-- The 16 Gulf of Finland routes of 20261017020100_seed_gulf_cables.sql (its `source` column names one of two datasets).
update public.cables set
  region_id = 'gulf-of-finland',
  licence = case when source like 'EMODnet%' then 'CC BY 4.0' else 'ODbL 1.0' end,
  source_url = case when source like 'EMODnet%' then 'https://emodnet.ec.europa.eu/en/human-activities' else 'https://www.openstreetmap.org/copyright' end
where region_id is null;

-- Those routes run whole cables out to 18 E (Nord Stream 1, BCS North), into the Central Baltic box. Clipped to the Gulf
-- box plus the 0.1 degree margin every seed uses (SEED_OPTIONS in src/data/regions/seed-options.ts), so no stretch of
-- seabed carries the same cable twice and the detector counts each crossing once. A route with nothing inside is kept.
update public.cables as cable set
  route = extensions.st_multi(
    extensions.st_collectionextract(extensions.st_intersection(cable.route::extensions.geometry, extensions.st_expand(region.box, 0.1)), 2)
  )::extensions.geography
from public.watched_regions as region
where region.id = cable.region_id
  and region.id = 'gulf-of-finland'
  and not extensions.st_within(cable.route::extensions.geometry, extensions.st_expand(region.box, 0.1))
  and not extensions.st_isempty(extensions.st_collectionextract(extensions.st_intersection(cable.route::extensions.geometry, extensions.st_expand(region.box, 0.1)), 2));

alter table public.cables
  alter column region_id set not null,
  alter column licence set not null,
  alter column source_url set not null;
alter table public.cables drop constraint cables_name_kind_key;
alter table public.cables add constraint cables_region_name_kind_key unique (region_id, name, kind);
create index cables_region_index on public.cables (region_id);
